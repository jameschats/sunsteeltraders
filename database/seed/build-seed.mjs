// Generates migrations/010_catalog_seed.sql from seed/catalog.json.
// catalog.json is the single source for the seeded catalogue; the web dev mock reads it too.
// Usage: node database/seed/build-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const c = JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));
const q = (v) => (v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
const j = (v) => q(JSON.stringify(v));
const out = [];
out.push(`-- =====================================================================
-- 010_catalog_seed.sql  —  GENERATED by database/seed/build-seed.mjs from
-- seed/catalog.json. Do not edit by hand. ${c.silos.length} silos, ${c.materials.length} materials,
-- ${c.products.length} products, IS 808 sections and ${c.cities.length} city pages.
-- Chemistry and mechanical values are typical standard ranges; the sales
-- team verifies them in the admin before launch.
-- =====================================================================`);
out.push('INSERT IGNORE INTO `Silos` (`SiloKey`,`Name`,`ShortName`,`Glyph`,`Intro`,`TopGrades`,`DisplayOrder`) VALUES');
out.push(c.silos.map((s) => ` (${q(s.key)},${q(s.name)},${q(s.short)},${q(s.glyph)},${q(s.intro)},${q(s.top)},${s.sort})`).join(',\n') + ';\n');
out.push('INSERT IGNORE INTO `Materials` (`MaterialKey`,`Name`,`Density`,`DisplayOrder`) VALUES');
out.push(c.materials.map((m, i) => ` (${q(m.key)},${q(m.name)},${m.density},${i + 1})`).join(',\n') + ';\n');
for (const p of c.products) {
  out.push(`INSERT IGNORE INTO \`Products\` (\`SiloId\`,\`Slug\`,\`Sku\`,\`Name\`,\`Grade\`,\`MaterialKey\`,\`Forms\`,\`SizeRange\`,\`Applications\`,\`Condition\`,\`Machinability\`,\`ChemistryJson\`,\`MechanicalJson\`,\`EquivalentsJson\`,\`StockStatus\`,\`DisplayOrder\`)
SELECT SiloId,${q(p.slug)},${q(p.sku)},${q(p.name)},${q(p.grade)},${q(p.material)},${q(p.forms.join(','))},${q(p.sizeRange)},${q(p.applications)},${q(p.condition)},${q(p.machinability)},${j(p.chemistry)},${j(p.mechanical)},${j(p.equivalents)},${q(p.stock)},${p.sort} FROM Silos WHERE SiloKey = ${q(p.silo)};`);
}
out.push('\nINSERT IGNORE INTO `SectionWeights` (`Designation`,`Kind`,`KgPerMetre`,`DisplayOrder`) VALUES');
out.push([...c.sections.beam.map((s, i) => ` (${q(s[0])},'beam',${s[1]},${i + 1})`), ...c.sections.channel.map((s, i) => ` (${q(s[0])},'channel',${s[1]},${i + 1})`)].join(',\n') + ';\n');
out.push('INSERT IGNORE INTO `Cities` (`Slug`,`Name`,`DistanceKm`,`LeadTime`,`Zones`,`Intro`,`IndustriesJson`,`PopularSlugsJson`,`DisplayOrder`) VALUES');
out.push(c.cities.map((x, i) => ` (${q(x.slug)},${q(x.name)},${x.km},${q(x.lead)},${q(x.zones)},${q(x.intro)},${j(x.inds)},${j(x.pop)},${i + 1})`).join(',\n') + ';\n');
out.push('INSERT IGNORE INTO `DeliveryLeadTimes` (`City`,`LeadTime`,`DisplayOrder`) VALUES');
out.push(c.leadTimes.map((x, i) => ` (${q(x.city)},${q(x.lead)},${i + 1})`).join(',\n') + ';\n');
out.push(`INSERT INTO \`__schema_migrations\` (\`script_name\`)
SELECT '010_catalog_seed.sql'
WHERE NOT EXISTS (SELECT 1 FROM \`__schema_migrations\` WHERE \`script_name\` = '010_catalog_seed.sql');\n`);
writeFileSync(join(here, '..', 'migrations', '010_catalog_seed.sql'), out.join('\n'));
console.log(`010_catalog_seed.sql: ${c.products.length} products`);
